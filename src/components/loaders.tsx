/** 48px arc in currentColor (brand by default). Set text-white on brand or teal grounds. */
export function Spinner({
  className = "h-12 w-12 text-brand",
  label,
}: {
  className?: string;
  label?: string;
}) {
  return (
    <svg
      viewBox="0 0 48 48"
      className={className}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      <circle
        cx="24"
        cy="24"
        r="20"
        fill="none"
        stroke="currentColor"
        strokeOpacity=".18"
        strokeWidth="4"
      />
      <g className="ld-spinner">
        <circle
          cx="24"
          cy="24"
          r="20"
          fill="none"
          stroke="currentColor"
          strokeWidth="4"
          strokeLinecap="round"
          strokeDasharray="40 126"
          transform="rotate(-90 24 24)"
        />
      </g>
    </svg>
  );
}

/** The logomark breathing while a whole area loads. Centred on the canvas at 120–160px. */
export function Splash({ className = "h-32 w-32" }: { className?: string }) {
  return (
    <svg viewBox="0 0 200 200" className={className} aria-hidden>
      <g className="ld-splash">
        {SPLASH.map((p, i) => (
          <path key={i} d={p.d} fill={p.fill} className={p.className} />
        ))}
      </g>
    </svg>
  );
}

/** Whole-area loading: the splash centred on the canvas, shown only past 300ms. */
export function SplashScreen() {
  return (
    <div
      className="ld-delayed flex min-h-[70dvh] items-center justify-center bg-canvas"
      aria-busy="true"
    >
      <Splash />
    </div>
  );
}

/** Generic page skeleton: a title, a row of cards and a list, inside white cards as skeleton.md asks. */
export function PageSkeleton({
  cards = 3,
  rows = 4,
}: {
  cards?: number;
  rows?: number;
}) {
  return (
    <div className="ld-delayed" aria-busy="true">
      <div aria-hidden>
        <Skeleton className="h-7 w-56 max-w-full" />
        <Skeleton className="mt-3 h-3 w-80 max-w-full" />
        {cards > 0 && (
          <div className="mt-8 grid gap-4 sm:grid-cols-3">
            {Array.from({ length: cards }, (_, i) => (
              <div
                key={i}
                className="rounded-2xl border border-line bg-white p-5 shadow-card"
              >
                <Skeleton className="h-3 w-24" />
                <Skeleton className="mt-4 h-6 w-16" />
              </div>
            ))}
          </div>
        )}
        <div className="mt-6 divide-y divide-line rounded-2xl border border-line bg-white shadow-card">
          {Array.from({ length: rows }, (_, i) => (
            <div key={i} className="flex items-center gap-4 p-5">
              <Skeleton className="h-11 w-11 shrink-0 rounded-full" />
              <div className="min-w-0 flex-1">
                <Skeleton className="h-4 w-1/3" />
                <Skeleton className="mt-2.5 h-3 w-2/3" />
              </div>
              <Skeleton className="hidden h-11 w-28 rounded-xl sm:block" />
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
